// The console's browser terminal reaches the device over WireGuard and SSHes
// in as the device's SSH user with the gateway key or a certificate from the
// organization's SSH CA. ssh.authorized_keys keeps the lines MeteorCloud
// manages in that user's ~/.ssh/authorized_keys current, as the Python agent
// did, and touches nothing else. The account is the ssh_user in root-owned
// config.json (set by the installer), never one the agent names.

// Comments that mark the managed lines.
const (
	gatewayKeyComment       = "meteorcloud-gateway"
	caKeyComment            = "meteorcloud-ca"
	legacyGatewayKeyComment = "meteorcloud-shell-gateway" // generated by Ansible and the docs
	authorizedKeysTemp      = "authorized_keys.meteorcloud"
)

// principalRe is an SSH certificate principal (device-<uuid> today).
var principalRe = regexp.MustCompile(`^[A-Za-z0-9._@-]{1,128}$`)

// SSHKeysRequest is the params of ssh.authorized_keys. Empty fields change
// nothing, so a call with none only reports the trusted CA.
type SSHKeysRequest struct {
	GatewayKey        string `json:"gateway_key"`
	GatewayKeyRetired bool   `json:"gateway_key_retired"`
	CAKey             string `json:"ca_key"`
	Principal         string `json:"principal"`
}

// SSHKeysReply says which CA ("<type> <base64>") the account trusts now.
type SSHKeysReply struct {
	User      string `json:"user"`
	TrustedCA string `json:"trusted_ca"`
	Changed   bool   `json:"changed"`
}

// keyOf returns "<type> <base64>" of an authorized_keys line (with or without
// options), or "".
func keyOf(line string) string {
	f := strings.Fields(line)
	for i := 0; i+1 < len(f); i++ {
		if strings.HasPrefix(f[i], "ssh-") || strings.HasPrefix(f[i], "ecdsa-") || strings.HasPrefix(f[i], "sk-") {
			return f[i] + " " + f[i+1]
		}
	}
	return ""
}

func lastField(line string) string {
	f := strings.Fields(line)
	if len(f) == 0 {
		return ""
	}
	return f[len(f)-1]
}

func isGatewayLine(l string) bool {
	c := lastField(l)
	return c == gatewayKeyComment || c == legacyGatewayKeyComment
}

func isCALine(l string) bool { return lastField(l) == caKeyComment }

// syncKeyLines is the Python agent's sync_authorized_keys on a list of lines:
// lines are added or replaced, and removed only when the server says so (the
// gateway key retired), so an older server or a partial answer never locks the
// operator out. It returns the new lines and the trusted CA.
func syncKeyLines(lines []string, r SSHKeysRequest) ([]string, string) {
	out := append([]string(nil), lines...)
	gateway := keyOf(r.GatewayKey)
	if r.GatewayKeyRetired {
		out = filterLines(out, isGatewayLine)
	} else if gateway != "" {
		present := false
		for _, l := range out {
			present = present || keyOf(l) == gateway
		}
		if !present {
			out = append(filterLines(out, isGatewayLine), gateway+" "+gatewayKeyComment)
		}
	}
	if ca := keyOf(r.CAKey); ca != "" && r.Principal != "" {
		wanted := `cert-authority,principals="` + r.Principal + `" ` + ca + " " + caKeyComment
		present := false
		for _, l := range out {
			present = present || l == wanted
		}
		if !present {
			out = append(filterLines(out, isCALine), wanted)
		}
	}
	for _, l := range out {
		if isCALine(l) {
			return out, keyOf(l)
		}
	}
	return out, ""
}

func filterLines(lines []string, drop func(string) bool) []string {
	var out []string
	for _, l := range lines {
		if !drop(l) {
			out = append(out, l)
		}
	}
	return out
}

func (r SSHKeysRequest) validate() error {
	for _, k := range []string{r.GatewayKey, r.CAKey} {
		if k != "" && (len(k) > 4096 || !sshKeyRe.MatchString(strings.TrimSpace(k))) {
			return badRequest("keys must be one SSH public key line")
		}
	}
	if r.Principal != "" && !principalRe.MatchString(r.Principal) {
		return badRequest("invalid principal")
	}
	return nil
}

// sshUser is the account the console's terminal uses, from config.json.
func (h Host) sshUser() (string, UserInfo, error) {
	path := h.ConfigFile
	if path == "" {
		path = config.DefaultPaths("").ConfigFile
	}
	c, err := config.Load(path)
	if err != nil || c.SSHUser == "" {
		return "", UserInfo{}, localrpc.Errorf(CodeUnsupported, "no ssh_user in %s (sudo meteorcli config --ssh-user NAME)", path)
	}
	if err := validUsername(c.SSHUser); err != nil {
		return "", UserInfo{}, err
	}
	info, err := h.LookupUser(c.SSHUser)
	if err != nil {
		return "", UserInfo{}, localrpc.Errorf(localrpc.CodeFailed, "ssh_user %q: %v", c.SSHUser, err)
	}
	return c.SSHUser, info, nil
}

func (h Host) sshAuthorizedKeys(_ context.Context, _ localrpc.Peer, raw json.RawMessage) (any, error) {
	var r SSHKeysRequest
	if err := decode(raw, &r); err != nil {
		return nil, err
	}
	if err := r.validate(); err != nil {
		return nil, err
	}
	name, info, err := h.sshUser()
	if err != nil {
		return nil, err
	}
	usersMu.Lock()
	defer usersMu.Unlock()
	home, err := openHome(info)
	if err != nil {
		return nil, err
	}
	defer home.Close()
	existing, err := readAuthorizedKeys(home)
	if err != nil {
		return nil, err
	}
	lines, ca := syncKeyLines(existing, r)
	reply := SSHKeysReply{User: name, TrustedCA: ca}
	if strings.Join(lines, "\n") == strings.Join(existing, "\n") {
		return reply, nil
	}
	if err := writeAuthorizedKeys(home, info, lines); err != nil {
		return nil, err
	}
	reply.Changed = true
	return reply, nil
}

// openHome opens the user's home so no path component can be swapped for a
// symlink that leaves it.
func openHome(info UserInfo) (*os.Root, error) {
	if !filepath.IsAbs(info.Home) {
		return nil, fmt.Errorf("authorized_keys: home %q is not an absolute path", info.Home)
	}
	st, err := os.Lstat(info.Home)
	if err != nil {
		return nil, fmt.Errorf("authorized_keys: %w", err)
	}
	if !st.IsDir() {
		return nil, fmt.Errorf("authorized_keys: home %q is not a real directory", info.Home)
	}
	return os.OpenRoot(info.Home)
}

func readAuthorizedKeys(home *os.Root) ([]string, error) {
	f, err := home.Open(".ssh/authorized_keys")
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("authorized_keys: %w", err)
	}
	defer f.Close()
	data, err := io.ReadAll(io.LimitReader(f, 1<<20))
	if err != nil {
		return nil, fmt.Errorf("authorized_keys: %w", err)
	}
	text := strings.TrimRight(string(data), "\n")
	if text == "" {
		return nil, nil
	}
	return strings.Split(text, "\n"), nil
}

// writeAuthorizedKeys replaces the file atomically, owned by the user, 0600.
func writeAuthorizedKeys(home *os.Root, info UserInfo, lines []string) error {
	if err := home.Mkdir(".ssh", 0o700); err != nil && !errors.Is(err, fs.ErrExist) {
		return fmt.Errorf("authorized_keys: %w", err)
	}
	dir, err := home.Open(".ssh")
	if err != nil {
		return fmt.Errorf("authorized_keys: %w", err)
	}
	defer dir.Close()
	if st, err := dir.Stat(); err != nil || !st.IsDir() {
		return errors.New("authorized_keys: ~/.ssh is not a directory")
	}
	if err := dir.Chown(info.UID, info.GID); err != nil {
		return fmt.Errorf("authorized_keys: %w", err)
	}
	ssh, err := home.OpenRoot(".ssh")
	if err != nil {
		return fmt.Errorf("authorized_keys: %w", err)
	}
	defer ssh.Close()
	_ = ssh.Remove(authorizedKeysTemp)
	f, err := ssh.OpenFile(authorizedKeysTemp, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		return fmt.Errorf("authorized_keys: %w", err)
	}
	_, err = f.WriteString(strings.Join(lines, "\n") + "\n")
	err = errors.Join(err, f.Chown(info.UID, info.GID), f.Sync(), f.Close())
	if err == nil {
		// os.Root has no Rename before Go 1.25: rename inside the opened .ssh.
		err = syscall.Renameat(int(dir.Fd()), authorizedKeysTemp, int(dir.Fd()), "authorized_keys")
	}
	if err != nil {
		_ = ssh.Remove(authorizedKeysTemp)
		return fmt.Errorf("authorized_keys: %w", err)
	}
	return nil
}

// auditSSHKeys logs what changes, not the keys.
func auditSSHKeys(raw json.RawMessage) []any {
	var r SSHKeysRequest
	_ = json.Unmarshal(raw, &r)
	return []any{"gateway_key", r.GatewayKey != "", "gateway_key_retired", r.GatewayKeyRetired, "ca_key", r.CAKey != ""}
}
